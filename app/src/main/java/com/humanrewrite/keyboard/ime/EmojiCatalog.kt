    private val paint = Paint()

    // Characters below U+1F000 default to text style, so VS16 asks for the colour emoji glyph.
    private fun glyph(codePoint: Int): String {
        val s = String(Character.toChars(codePoint))
        return if (codePoint < 0x1F000) s + "️" else s
    }

    private fun renders(s: String) = paint.hasGlyph(s)

